import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import {parseTemplate} from '@angular/compiler';
const source=readFileSync(new URL('../src/app/features/catalogo/catalog-list.component.ts',import.meta.url),'utf8');
const exports={};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,experimentalDecorators:true}}).outputText,
  {exports,require:name=>name==='@angular/core'?{Component:()=>value=>value}:new Proxy({},{get:()=>class{}})});
const component=Object.create(exports.CatalogListComponent.prototype);
let permissions=[];
let config={endpoint:'cancha-deportes',permission:'canchas',state:'activo'};
Object.assign(component,{config:()=>config,auth:{can:(permission,global)=>permissions.includes(permission)&&(!global||permissions.includes('alcance.global'))}});
assert.equal(component.hasActions({activo:true}),false,'Cashier has no actions on court sports');
config={...config,endpoint:'canchas'};
assert.equal(component.hasActions({activa:true}),true,'Cashier retains View court');
config={...config,endpoint:'cancha-deportes'};permissions=['canchas.editar'];
assert.equal(component.hasActions({activo:false}),true,'Editor retains Edit for inactive rows');
permissions=['canchas.desactivar'];
assert.equal(component.hasActions({activo:true}),true);
assert.equal(component.hasActions({activo:false}),false,'Inactive rows cannot show empty deactivation menu');
config={endpoint:'politicas',permission:'politicas',state:'activa'};permissions=['politicas.desactivar'];
assert.equal(component.hasActions({activa:true}),false);
permissions=['politicas.editar'];assert.equal(component.hasActions({activa:true}),true);
config={endpoint:'versiones',permission:'politicas',versioned:true};permissions=['politicas.crear'];
assert.equal(component.hasActions({activo:true}),true);
config={endpoint:'deportes',permission:'deportes',global:true};permissions=['deportes.editar'];
assert.equal(component.hasActions({activo:true}),false);
permissions.push('alcance.global');assert.equal(component.hasActions({activo:true}),true);
const template=source.match(/template:`([\s\S]*?)`,\s*\}\)/)[1];
assert.equal(parseTemplate(template,'catalog-actions').errors,null);
assert.match(template,/@if\(showActions\(\)\)\{<th>Acciones<\/th>\}/);
assert.match(template,/@if\(hasActions\(row\)\)\{<div class="catalog-actions">/);
console.log('Catalog actions: read-only cashier, court detail, edit, deactivation, inactive rows, policies and global permissions passed without browser.');
